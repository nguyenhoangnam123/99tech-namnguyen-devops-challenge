// Pure rendering of SLO results: verdicts, the markdown report and the
// JSON capture. No I/O here; the runner writes what these return.
import { SERVICE_GROUPS, SIGNALS } from './mimir.mjs';

export function toSeconds(window) {
  const match = /^(\d+)(s|m)$/.exec(window);
  if (!match) throw new Error(`Unsupported window ${window}`);
  return Number(match[1]) * (match[2] === 'm' ? 60 : 1);
}

// Same rules as the k6 thresholds. Dropped iterations mean the offered
// load was never sent; a latency without its cost is not a result.
export function verdictOf({ scenario, latency, resources, failed }) {
  if (failed) return `failed: ${failed}`;
  if (resources.error) return `incomplete: ${resources.error}`;
  const { slo } = scenario;
  const ok =
    latency.p95 <= slo.p95Ms &&
    latency.p99 <= slo.p99Ms &&
    latency.errorRate < slo.errorRate &&
    latency.dropped === 0;
  return ok ? 'met' : 'missed';
}

export function consoleLine(row) {
  const { latency } = row;
  if (!latency) return verdictOf(row);
  const { p95, p99, errorRate, dropped, requestRate } = latency;
  return `p95 ${p95.toFixed(1)} ms, p99 ${p99.toFixed(1)} ms, ${Math.round(requestRate)} req/s, errors ${errorRate}, dropped ${dropped}: ${verdictOf(row)}`;
}

// Everything the report shows, as data, for later comparison.
export function captured(rows, { commit, telemetry }) {
  return {
    commit,
    telemetry,
    generatedAt: new Date().toISOString(),
    scenarios: rows.map(({ scenario, window, latency, resources, failed, ...measured }) => ({
      id: scenario.id,
      window,
      offered: loadOf(scenario),
      slo: scenario.slo,
      verdict: verdictOf({ scenario, latency, resources, failed }),
      latency,
      resources,
      ...measured,
    })),
  };
}

export function render(rows, { commit, telemetry, grafana }) {
  const lines = [
    '# SLO results',
    '',
    `Commit ${commit}, ${new Date().toISOString().slice(0, 16)}Z, local Docker stack with \`make up-obs\`,`,
    `tracing ${telemetry}. Generated by \`make slo\`; scenarios are in`,
    '[tests/perf/slo/scenarios.json](../../tests/perf/slo/scenarios.json).',
    '',
    'Latency is per request at the edge (k6), load phase only. CPU is % of one core, summed',
    'over replicas; memory is the container working set. Both cover the load window only.',
    '',
    '| Scenario | Offered load | Window | Size | SLO p95 / p99 | Measured p95 / p99 | Req/s | Errors | Dropped | Verdict |',
    '|---|---|---|---|---|---|---:|---:|---:|---|',
    ...rows.map(summaryRow),
  ];
  for (const row of rows.filter(({ resources }) => resources)) {
    const { scenario, resources, agent, pipeline, host, span, window } = row;
    lines.push('', `## ${scenario.id}: ${scenario.title}`, '');
    lines.push(windowLine(span, grafana), '');
    if (host) lines.push(hostLine(host), '');
    if (pipeline) lines.push(pipelineLine(pipeline), '');
    if (agent) lines.push(agentLine(agent, toSeconds(window)), '');
    if (resources.error) {
      lines.push(`Resources unavailable: ${resources.error}`);
      continue;
    }
    lines.push('| Group | Service | CPU avg | CPU max | Memory avg | Memory max |');
    lines.push('|---|---|---:|---:|---:|---:|');
    for (const [group, services] of Object.entries(SERVICE_GROUPS)) {
      for (const service of services) lines.push(resourceRow(group, service, resources[service]));
    }
  }
  return `${lines.join('\n')}\n`;
}

// Offered actions, not requests: a cancel first lists open orders, so it
// sends two. The measured request rate is its own column.
function loadOf({ load }) {
  if (load.model === 'concurrent')
    return `${load.vus} concurrent traders, ${load.thinkMs} ms think`;
  const total = Object.values(load.rates).reduce((a, b) => a + b, 0);
  return `${total} actions/s`;
}

function summaryRow(row) {
  const { scenario, window, latency } = row;
  const { slo, size } = scenario;
  const verdict = verdictOf(row);
  const shown = verdict === 'met' ? 'met' : `**${verdict}**`;
  const sizeText = `depth ${size.depthLevels}, book ${size.bookLevels}`;
  const head = `| ${scenario.id} | ${loadOf(scenario)} | ${window} | ${sizeText} | ${slo.p95Ms} / ${slo.p99Ms} ms`;
  if (!latency) return `${head} | | | | | ${shown} |`;
  const ms = (n) => `${n.toFixed(1)} ms`;
  const errors = `${(latency.errorRate * 100).toFixed(3)}%`;
  const rate = Math.round(latency.requestRate);
  return `${head} | ${ms(latency.p95)} / ${ms(latency.p99)} | ${rate} | ${errors} | ${latency.dropped} | ${shown} |`;
}

function windowLine({ from, to }, grafana) {
  const at = (ms) => new Date(ms).toISOString().slice(11, 19);
  const board = (uid) => `${grafana}/d/${uid}?from=${Math.round(from)}&to=${Math.round(to)}`;
  return `Window ${at(from)} to ${at(to)} UTC: [latency](${board('exchange-slo')}), [resources](${board('exchange-resources')}).`;
}

function hostLine(host) {
  const pct = (n) => `${(n * 100).toFixed(1)}%`;
  const gib = (host.minAvailableBytes / 2 ** 30).toFixed(1);
  const swap = Math.round(host.swapInPerSecond ?? 0);
  return (
    `Docker VM stall time: CPU ${pct(host.cpu)}, memory ${pct(host.memory)} (full ${pct(host.memoryFull)}), ` +
    `IO ${pct(host.io)} (full ${pct(host.ioFull)}); swap-in ${swap} pages/s; min available ${gib} GiB.`
  );
}

// Histograms stop at 10 s; a p99 at the top bucket means "at least".
function pipelineLine({ toMatcherP99, toSettledP99, outboxBacklogMax }) {
  const ms = (s) => {
    if (s === undefined) return 'n/a';
    return s >= 10 ? '≥ 10 s' : `${Math.round(s * 1000)} ms`;
  };
  const backlog = outboxBacklogMax === undefined ? 'n/a' : `${outboxBacklogMax} rows`;
  return `Pipeline p99: command to matcher ${ms(toMatcherP99)}, to settled ${ms(toSettledP99)}; outbox backlog max ${backlog}.`;
}

function agentLine(agent, seconds) {
  const parts = Object.entries(SIGNALS).map(([signal, label]) => {
    const { accepted, lost } = agent[signal];
    if (!accepted && !lost) return `no ${label}`;
    const share = (lost / ((accepted ?? 0) + lost)) * 100;
    return `${Math.round((accepted ?? 0) / seconds)} ${label}/s, ${share.toFixed(2)}% lost`;
  });
  return `Telemetry agent: ${parts.join('; ')}.`;
}

function resourceRow(group, service, r) {
  const pct = (n) => (n === undefined ? 'n/a' : `${n.toFixed(1)}%`);
  const mib = (n) => (n === undefined ? 'n/a' : `${Math.round(n / 2 ** 20)} MiB`);
  return `| ${group} | ${service} | ${pct(r.cpuAvg)} | ${pct(r.cpuMax)} | ${mib(r.memAvg)} | ${mib(r.memMax)} |`;
}
